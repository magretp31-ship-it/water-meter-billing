-- ICT371 QUESTION 7: WATER METER READINGS AND BILLING
-- Tariff: first 10 units K5 each; units above 10 K8 each.

DROP VIEW IF EXISTS v_overdue_bills CASCADE;
DROP TABLE IF EXISTS receivable_snapshot, bills, readings, customers CASCADE;

CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL
);

CREATE TABLE readings (
    reading_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
    reading_month DATE NOT NULL CHECK (EXTRACT(DAY FROM reading_month) = 1),
    previous_reading NUMERIC(12,2) NOT NULL CHECK (previous_reading >= 0),
    current_reading NUMERIC(12,2) NOT NULL CHECK (current_reading >= 0),
    UNIQUE(customer_id, reading_month)
);

CREATE TABLE bills (
    bill_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id INTEGER NOT NULL UNIQUE REFERENCES readings(reading_id),
    charge NUMERIC(12,2) NOT NULL CHECK (charge >= 0),
    amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0 AND amount_paid <= charge),
    due_on DATE NOT NULL
);

CREATE TABLE receivable_snapshot (
    snapshot_date DATE PRIMARY KEY,
    total_due NUMERIC(14,2) NOT NULL DEFAULT 0
);

-- (d) Reject meter readings that move backwards, including direct SQL.
CREATE OR REPLACE FUNCTION fn_validate_meter_reading()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.current_reading < NEW.previous_reading THEN
        RAISE EXCEPTION 'Current meter reading cannot be below previous reading';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_meter_reading
BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW EXECUTE FUNCTION fn_validate_meter_reading();

-- (b) Two-band tariff.
CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
BEGIN
    IF p_units IS NULL OR p_units < 0 THEN
        RAISE EXCEPTION 'Consumption must be zero or positive';
    END IF;

    IF p_units <= 10 THEN
        RETURN ROUND(p_units * 5, 2);
    ELSE
        RETURN ROUND(10 * 5 + (p_units - 10) * 8, 2);
    END IF;
END;
$$;

-- (c) Generate one bill per reading.
CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id INTEGER, p_due_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_previous NUMERIC(12,2); v_current NUMERIC(12,2);
BEGIN
    SELECT previous_reading, current_reading
    INTO v_previous, v_current
    FROM readings WHERE reading_id = p_reading_id;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading ID: %', p_reading_id; END IF;
    IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date is required'; END IF;
    IF EXISTS (SELECT 1 FROM bills WHERE reading_id = p_reading_id) THEN
        RAISE EXCEPTION 'A bill already exists for reading %', p_reading_id;
    END IF;

    INSERT INTO bills(reading_id, charge, amount_paid, due_on)
    VALUES (p_reading_id, fn_water_charge(v_current - v_previous), 0, p_due_on);
END;
$$;

