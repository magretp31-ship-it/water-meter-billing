-- (e) Overdue unpaid balances.
CREATE OR REPLACE VIEW v_overdue_bills AS
SELECT c.full_name AS customer_name, b.due_on,
       (b.charge - b.amount_paid) AS outstanding_amount
FROM bills b
JOIN readings r ON r.reading_id = b.reading_id
JOIN customers c ON c.customer_id = r.customer_id
WHERE b.due_on < CURRENT_DATE AND b.amount_paid < b.charge;

SELECT * FROM v_overdue_bills;

-- (f) Date-based unpaid-bill index.
CREATE INDEX idx_bills_due_unpaid
ON bills(due_on) WHERE amount_paid < charge;

EXPLAIN
SELECT bill_id, reading_id, charge - amount_paid AS outstanding
FROM bills
WHERE due_on < CURRENT_DATE AND amount_paid < charge;

-- (g) Today's total unpaid balances; rerun replaces today's row.
CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO receivable_snapshot(snapshot_date, total_due)
    SELECT CURRENT_DATE, COALESCE(SUM(charge - amount_paid), 0)
    FROM bills
    WHERE amount_paid < charge
    ON CONFLICT (snapshot_date) DO UPDATE
    SET total_due = EXCLUDED.total_due;
END;
$$;

